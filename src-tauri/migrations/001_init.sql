CREATE TABLE sessions (
    id                TEXT PRIMARY KEY,
    name              TEXT NOT NULL,
    source_kind       TEXT NOT NULL,
    source_ref        TEXT NOT NULL DEFAULT '',
    id_mode           TEXT NOT NULL,
    options           TEXT NOT NULL,
    status            TEXT NOT NULL,
    error             TEXT,
    created_at        TEXT NOT NULL,
    started_at        TEXT,
    finished_at       TEXT,
    remote_session_id TEXT,
    sync_error        TEXT
);

CREATE TABLE items (
    id                INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id        TEXT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    seq               INTEGER NOT NULL,
    event_id          TEXT NOT NULL,
    front_path        TEXT NOT NULL,
    back_path         TEXT,
    thumb_path        TEXT,
    preview_path      TEXT,
    back_preview_path TEXT,
    status            TEXT NOT NULL,
    id_type           TEXT,
    name              TEXT,
    full_name         TEXT,
    set_name          TEXT,
    set_code          TEXT,
    card_number       TEXT,
    series            TEXT,
    year              TEXT,
    subcategory       TEXT,
    confidence        TEXT,
    distance          REAL,
    price             REAL,
    grade             REAL,
    condition         TEXT,
    recognition       TEXT,
    grading           TEXT,
    grading_job_id    TEXT,
    grading_images    TEXT,
    error             TEXT,
    calls             INTEGER NOT NULL DEFAULT 0,
    analyzed_at       TEXT,
    rev               INTEGER NOT NULL DEFAULT 0,
    synced_rev        INTEGER NOT NULL DEFAULT 0,
    image_synced      INTEGER NOT NULL DEFAULT 0,
    created_at        TEXT NOT NULL,
    updated_at        TEXT NOT NULL,
    UNIQUE (session_id, seq)
);

CREATE INDEX items_session_status ON items (session_id, status);
